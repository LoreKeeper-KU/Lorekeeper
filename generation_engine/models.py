# These classes store the information used by the LoreKeeper workflow.
# They are simple data containers for now.

from dataclasses import dataclass, field
from typing import Literal
from uuid import uuid4

from shared.schemas import CanonFact, VerificationReport, VisualAsset

@dataclass
class DemoRequest:
    # The user's request, for example:
    # "Write a scene where Princess Amina defends her castle."
    prompt: str

    # The workflow mode:
    # "basic"    = generate only
    # "rag"      = retrieve canon and generate
    # "verified" = retrieve, generate, check, repair and recheck
    mode: str = "verified"

    # The maximum number of times the system may repair a scene.
    max_repair_attempts: int = 3
    world_id: str = "world_001"


@dataclass
class Scene:
    # A unique name for the generated scene.
    scene_id: str

    # The actual story or dialogue generated by the system.
    text: str

    # The version number of the scene.
    # The first version is 0. Each repair increases the number.
    revision: int = 0



@dataclass
class PipelineResult:
    # Final result status:
    # "verified", "needs_review", "unverified", or "error"
    status: str

    # The scene before any repair.
    initial_scene: Scene

    # The latest version after repair attempts.
    final_scene: Scene

    # All verification reports created during the workflow.
    reports: list[VerificationReport] = field(default_factory=list)

    # Number of repairs performed.
    repair_attempts: int = 0


@dataclass
class ChatMessage:
    role: Literal["user", "assistant"]
    content: str
    world_id: str
    kind: str = "message"
    id: str = field(default_factory=lambda: uuid4().hex)
    source_scene_id: str | None = None
    pipeline: PipelineResult | None = None
    asset: VisualAsset | None = None
    visual_status: str = "not_requested"
    visual_notes: list[str] = field(default_factory=list)


@dataclass
class PendingCanon:
    world_id: str
    name: str
    facts: list[CanonFact]
    proposal_ids: list[str]
    message_id: str | None = None


@dataclass
class ConversationState:
    world_id: str
    focus_entity_ids: list[str] = field(default_factory=list)
    unfinished_task: str = ""
    task_request: str = ""
    last_question: str = ""


@dataclass
class ChatRequest:
    message: str
    world_id: str = "world_001"
    history: list[ChatMessage] = field(default_factory=list)
    active_scene_id: str | None = None
    pending_canon: PendingCanon | None = None
    conversation: ConversationState | None = None


@dataclass
class ChatReply:
    message: ChatMessage
    active_scene_id: str | None = None
    pending_canon: PendingCanon | None = None
    conversation: ConversationState | None = None
