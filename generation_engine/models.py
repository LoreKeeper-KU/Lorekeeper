# These classes store the information used by the LoreKeeper workflow.
# They are simple data containers for now.

from dataclasses import dataclass, field

from shared.schemas import CanonFact, VerificationReport

@dataclass
class DemoRequest:
    # The user's request, for example:
    # "Write a scene where Princess Amina defends her castle."
    prompt: str

    # The workflow mode:
    # "basic"    = generate only
    # "rag"      = retrieve canon and generate
    # "verified" = retrieve, generate, check, repair and recheck
    mode: str = "verified"

    # The maximum number of times the system may repair a scene.
    max_repair_attempts: int = 3


@dataclass
class Scene:
    # A unique name for the generated scene.
    scene_id: str

    # The actual story or dialogue generated by the system.
    text: str

    # The version number of the scene.
    # The first version is 0. Each repair increases the number.
    revision: int = 0



@dataclass
class PipelineResult:
    # Final result status:
    # "verified", "needs_review", "unverified", or "error"
    status: str

    # The scene before any repair.
    initial_scene: Scene

    # The latest version after repair attempts.
    final_scene: Scene

    # All verification reports created during the workflow.
    reports: list[VerificationReport] = field(default_factory=list)

    # Number of repairs performed.
    repair_attempts: int = 0